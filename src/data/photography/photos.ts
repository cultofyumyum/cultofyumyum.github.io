export interface PhotoExif {
  camera?: string;
  lens?: string;
  focalLength?: string;
  aperture?: string;
  shutterSpeed?: string;
  iso?: number;
}

export interface PhotoItem {
  id: string;
  title: string;
  caption?: string;
  location?: string;
  date: string; // YYYY-MM-DD
  category: string;
  aspectRatio: 'portrait' | 'landscape' | 'square';
  width: number;
  height: number;
  /** Low-res preview / thumbnail URL (e.g., 600px wide WebP) */
  thumbUrl: string;
  /** Full-res display URL (e.g., 1800px wide WebP) */
  fullUrl: string;
  /** Dominant color hex for instant blur placeholder while loading */
  dominantColor: string;
  exif?: PhotoExif;
}

